"""Compile the Stage 2 contribution table; never edit upstream building definitions.

CSV is the extension API: one row per concrete building level, one chain identifier
for mutually exclusive upgrades, seven contributions. Stage 3 target and legacy
IDs share one branch so transitional wrappers cannot double-count. --check needs
no installed game. --audit-sources additionally checks IDs against the effective
local stack.
"""
from pathlib import Path
import argparse
import csv
import io
import json
import re

ROOT = Path(__file__).resolve().parents[1]
LEGACY_TABLE = ROOT / 'evidence/stage2/AAWC_REFORGING_STAGE2_BUILDING_CONTRIBUTIONS.csv'
STAGE3_TABLE = ROOT / 'catalogue/stage3/adapter_inputs.csv'
TABLE = STAGE3_TABLE
OUTPUT = ROOT / 'mod/AGOT_Alternate_World_Compatch/common/scripted_effects/aawc_stage2_building_contributions.txt'
CUSTOM_LOC_OUTPUT = ROOT / 'mod/AGOT_Alternate_World_Compatch/common/customizable_localization/aawc_stage2_building_contributions_custom_loc.txt'
LOCALIZATION_OUTPUT = ROOT / 'mod/AGOT_Alternate_World_Compatch/localization/english/aawc_stage2_building_contributions_l_english.yml'
DEPENDENCY_BUILDINGS = ROOT / 'dependencies/AAWC_Dependencies_Modpack/common/buildings'
DIMENSIONS = ('sustenance', 'habitation', 'opportunity', 'health', 'security', 'amenities')
FIELDS = (*DIMENSIONS, 'space_percent')
UNAVAILABLE_LEGACY_BUILDINGS = {
    *(f'powder_magazine_{tier:02}' for tier in range(1, 9)),
}


def rows():
    with TABLE.open(encoding='utf-8', newline='') as stream:
        result = list(csv.DictReader(stream))
    seen = set()
    for row in result:
        assert re.fullmatch(r'\w+', row['building']), row
        assert row['building'] not in seen, row['building']
        seen.add(row['building'])
        for field in FIELDS:
            float(row[field])
        assert int(row['level']) > 0
        assert row['purpose'] and row['source']
    expected = stage3_rows()
    if result != expected:
        raise ValueError('Stage 3 runtime input differs from the validated catalogue projection')
    legacy_ids = catalogue_legacy_ids()
    return [{**row, 'legacy_building': legacy_ids[row['building']]} for row in result]


def stage3_rows(data=None):
    """Project catalogue fields only; native-role metadata is never executable.

    Runtime rows must match this projection exactly before legacy lineage is added
    to the shared trigger. Construction, AI and native outputs remain separate.
    """
    import generate_aawc_stage3_catalogue as catalogue
    if data is None:
        data = catalogue.load_source(catalogue.SOURCE)
    catalogue.validate(data)
    result = []
    for chain in sorted(data['chains'], key=lambda c: c['id']):
        for level in sorted(chain['levels'], key=lambda l: l['tier']):
            capacity = level['capacity']
            if capacity['status'] != 'approved' or capacity['space_percent'] is None:
                raise ValueError(f"{level['id']}: settlement-space input is not approved")
            result.append({
                'building': level['id'], 'chain': chain['id'], 'level': str(level['tier']),
                **{field: format(level['conditions'][field], 'g') for field in DIMENSIONS},
                'space_percent': format(capacity['space_percent'], 'g'),
                'purpose': 'Stage 3 ' + chain['family'] + ' infrastructure',
                'source': 'catalogue/stage3/catalogue.json#' + level['id'],
            })
    return result


def catalogue_legacy_ids(data=None):
    """Return only effective legacy IDs that are safe for bounded dual reads.

    The recovered vanilla Powder Magazine lineage is not defined by AGOT's
    effective building stack. CK3 treats even a false ``has_building`` probe of
    an undefined ID as a script error, so those targets must be read directly.
    The catalogue retains their historical lineage for migration provenance.
    """
    import generate_aawc_stage3_catalogue as catalogue
    if data is None:
        data = catalogue.load_source(catalogue.SOURCE)
    catalogue.validate(data)
    return {
        level['id']: (
            None if level['legacy_id'] in UNAVAILABLE_LEGACY_BUILDINGS
            else level['legacy_id']
        )
        for chain in data['chains']
        for level in chain['levels']
    }


def render_input_table(records):
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=['building', 'chain', 'level', *FIELDS,
                                               'purpose', 'source'], lineterminator='\n')
    writer.writeheader()
    writer.writerows(records)
    return stream.getvalue()


def render(records):
    chains = {}
    for row in records:
        chains.setdefault(row['chain'], []).append(row)
    out = ['# Generated by scripts/generate_aawc_stage2_conditions.py from the validated Stage 3 adapter CSV.',
           '# Highest installed level per chain only. Different chains add independently.',
           '# A target and its legacy compatibility ID share one branch and can contribute only once.',
           '# Presence models physical infrastructure, not owner/faith-dependent income bonuses.',
           'aawc_stage2_building_contributions_effect = {']
    for chain, levels in sorted(chains.items()):
        out.append(f'\t# {chain}: {levels[0]["purpose"]}')
        for i, row in enumerate(sorted(levels, key=lambda r: int(r['level']), reverse=True)):
            out.append(f'\t{"if" if i == 0 else "else_if"} = {{')
            legacy = row.get('legacy_building')
            if legacy:
                out.extend(['\t\tlimit = {', '\t\t\tOR = {',
                            f'\t\t\t\thas_building = {row["building"]}',
                            f'\t\t\t\thas_building = {legacy}',
                            '\t\t\t}', '\t\t}'])
            else:
                out.append(f'\t\tlimit = {{ has_building = {row["building"]} }}')
            out.extend(['\t\taawc_stage2_add_contribution_effect = { ' +
                        ' '.join(f'{field.upper()} = {row[field]}' for field in FIELDS) + ' }', '\t}'])
    out.append('}')
    return '\n'.join(out) + '\n'


def format_contribution(value):
    number = float(value)
    rendered = f'{number:g}'
    return f'+{rendered}' if number > 0 else rendered


def render_building_custom_loc(records):
    out = ['# Generated by scripts/generate_aawc_stage2_conditions.py from the validated Stage 3 adapter CSV.',
           '# Each target/legacy pair exposes one exact contribution row used by Stage 2.']
    for row in sorted(records, key=lambda item: item['building']):
        building = row['building']
        out.extend([
            f'AAWC_Stage2Building_{building} = {{',
            '\ttype = province',
            '\ttext = {',
        ])
        legacy = row.get('legacy_building')
        if legacy:
            out.extend(['\t\ttrigger = {', '\t\t\tOR = {',
                        f'\t\t\t\thas_building = {building}',
                        f'\t\t\t\thas_building = {legacy}',
                        '\t\t\t}', '\t\t}'])
        else:
            out.append(f'\t\ttrigger = {{ has_building = {building} }}')
        out.extend([
            f'\t\tlocalization_key = aawc_stage2_building_{building}',
            '\t}',
            '\ttext = {',
            '\t\tfallback = yes',
            '\t\tlocalization_key = aawc_stage2_building_empty',
            '\t}',
            '}',
            '',
        ])
    return '\n'.join(out)


def render_building_localization(records, group_size=25):
    ordered = sorted(records, key=lambda item: item['building'])
    out = ['l_english:', ' aawc_stage2_building_empty:0 ""']
    for group_index, start in enumerate(range(0, len(ordered), group_size), 1):
        calls = ''.join(
            f"[HoldingView.GetProvince.Custom('AAWC_Stage2Building_{row['building']}')]"
            for row in ordered[start:start + group_size]
        )
        out.append(f' AAWC_STAGE2_BUILDING_LINES_{group_index:02}:0 "{calls}"')
    labels = {
        'sustenance': 'Sustenance',
        'habitation': 'Habitation',
        'opportunity': 'Opportunity',
        'health': 'Health',
        'security': 'Security',
        'amenities': 'Amenities',
        'space_percent': 'Settlement space',
    }
    for row in ordered:
        parts = []
        for field in FIELDS:
            if float(row[field]) == 0:
                continue
            value = format_contribution(row[field])
            color = 'P' if float(row[field]) > 0 else 'N'
            suffix = '%' if field == 'space_percent' else ''
            parts.append(f'#{color} {labels[field]} {value}{suffix}#!')
        detail = ', '.join(parts) if parts else '#high no score change#!'
        display_id = row.get('legacy_building') or row['building']
        out.append(f' aawc_stage2_building_{row["building"]}:0 "\\n${display_id}$: {detail}"')
    return '\n'.join(out) + '\n'


def find_matching_brace(text, open_brace):
    depth = 0
    in_comment = False
    in_string = False
    for index in range(open_brace, len(text)):
        char = text[index]
        if in_comment:
            if char == '\n':
                in_comment = False
            continue
        if in_string:
            if char == '"' and (index == 0 or text[index - 1] != '\\'):
                in_string = False
            continue
        if char == '#':
            in_comment = True
        elif char == '"':
            in_string = True
        elif char == '{':
            depth += 1
        elif char == '}':
            depth -= 1
            if depth == 0:
                return index
    raise ValueError('Could not find matching brace')


def iter_top_level_buildings(text):
    result = []
    index = 0
    depth = 0
    in_comment = False
    in_string = False
    pattern = re.compile(r'\s*([A-Za-z0-9_]+)\s*=\s*\{')
    while index < len(text):
        char = text[index]
        if in_comment:
            if char == '\n':
                in_comment = False
            index += 1
            continue
        if in_string:
            if char == '"' and (index == 0 or text[index - 1] != '\\'):
                in_string = False
            index += 1
            continue
        if char == '#':
            in_comment = True
            index += 1
            continue
        if char == '"':
            in_string = True
            index += 1
            continue
        if depth == 0:
            match = pattern.match(text, index)
            if match:
                open_brace = text.index('{', match.start())
                close_brace = find_matching_brace(text, open_brace)
                result.append((match.group(1), text[match.start():close_brace + 1].strip()))
                index = close_brace + 1
                continue
        if char == '{':
            depth += 1
        elif char == '}':
            depth -= 1
        index += 1
    return result


def effective_buildings(extra_roots=()):
    # Optional upstream roots come first; retained dependency and AAWC definitions
    # then apply the supported load-order overrides.
    roots = [Path(root) for root in extra_roots] + [DEPENDENCY_BUILDINGS, OUTPUT.parents[1] / 'buildings']
    files = {}
    for root in roots:
        for path in sorted(root.glob('*.txt')):
            files[path.name] = path  # same relative filename is replaced by later mod
    result = {}
    for path in sorted(files.values(), key=lambda p: p.name):
        for name, block in iter_top_level_buildings(path.read_text(encoding='utf-8-sig')):
            result[name] = (path, block)
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--stage3-inputs', action='store_true',
                        help='Export or check the canonical adapter CSV consumed by runtime generation.')
    parser.add_argument('--audit-sources', action='store_true')
    parser.add_argument(
        '--upstream-building-root', type=Path, action='append', default=[],
        help='Optional vanilla/AGOT common/buildings directory; repeat in load order.',
    )
    args = parser.parse_args()
    if args.stage3_inputs:
        if args.audit_sources:
            parser.error('--stage3-inputs is an inert export; runtime source audit is separate')
        records = stage3_rows()
        expected = render_input_table(records)
        if args.check:
            if not STAGE3_TABLE.exists() or STAGE3_TABLE.read_text(encoding='utf-8') != expected:
                raise SystemExit('Stage 3 adapter inputs are stale')
        else:
            STAGE3_TABLE.write_text(expected, encoding='utf-8', newline='\n')
        print(f'Stage 3 adapter input parity PASS: {len(records)} levels / 131 chains')
        return
    records = rows()
    if args.audit_sources:
        effective = effective_buildings(args.upstream_building_root)
        missing = sorted(
            row['building'] for row in records
            if row['building'] not in effective
            and (not row.get('legacy_building') or row['legacy_building'] not in effective)
        )
        if missing:
            raise SystemExit(f'Undefined building IDs: {missing}')
        print(f'Source IDs verified: {len(records)}')
    generated = render(records)
    generated_custom_loc = render_building_custom_loc(records)
    generated_localization = render_building_localization(records)
    if args.check:
        if OUTPUT.read_text(encoding='utf-8-sig') != generated:
            raise SystemExit('Stage 2 generated contributions are stale')
        if CUSTOM_LOC_OUTPUT.read_text(encoding='utf-8-sig') != generated_custom_loc:
            raise SystemExit('Stage 2 generated building custom localization is stale')
        if LOCALIZATION_OUTPUT.read_text(encoding='utf-8-sig') != generated_localization:
            raise SystemExit('Stage 2 generated building localization is stale')
    else:
        OUTPUT.write_text(generated, encoding='utf-8-sig', newline='\n')
        CUSTOM_LOC_OUTPUT.write_text(generated_custom_loc, encoding='utf-8-sig', newline='\n')
        LOCALIZATION_OUTPUT.write_text(generated_localization, encoding='utf-8-sig', newline='\n')
    print(f'Contribution parity PASS: {len(records)} levels / {len({r["chain"] for r in records})} chains')


if __name__ == '__main__':
    main()
