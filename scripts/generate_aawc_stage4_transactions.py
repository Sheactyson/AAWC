def cohort(band: str) -> str:
    return f"aawc_reforging_cohort_{band}"


def reserved(band: str) -> str:
    return f"aawc_stage4_reserved_{band}"


def pool(band: str) -> str:
    return f"aawc_reforging_transfer_{band}"


def attrition(band: str) -> str:
    return f"aawc_stage4_receipt_attrition_{band}"


def value_or_zero(name: str) -> str:
    return f"{{ value = 0 if = {{ limit = {{ has_variable = {name} }} add = var:{name} }} }}"


def render_values() -> str:
    out = [
        "# Generated by scripts/generate_aawc_stage4_transactions.py. Do not hand edit.",
        "",
        "aawc_stage4_reserved_packet_total = {",
        "\tvalue = 0",
    ]
    out.extend(f"\tadd = {value_or_zero(reserved(band))}" for band, _ in BANDS)
    out.extend(["}", "", "aawc_stage4_transfer_pool_total = {", "\tvalue = 0"])
    out.extend(f"\tadd = {value_or_zero(pool(band))}" for band, _ in BANDS)
    out.extend(["}", "", "aawc_stage4_unreserved_civilian_total = {", "\tvalue = 0"])
    for band, military in BANDS:
        inner = f"{{ value = var:{cohort(band)} subtract = {value_or_zero(reserved(band))}"
        if military:
            inner += f" subtract = {value_or_zero('aawc_reforging_' + military)}"
        inner += " min = 0 floor = yes }"
        out.append(f"\tadd = {inner}")
    out.extend(
        [
            "}",
            "",
            "aawc_stage4_receipt_reconciliation_delta = {",
            f"\tvalue = {value_or_zero('aawc_stage4_receipt_debited')}",
            f"\tsubtract = {value_or_zero('aawc_stage4_receipt_credited')}",
            f"\tsubtract = {value_or_zero('aawc_stage4_receipt_attrition')}",
            "}",
            "",
        ]
    )
    return "\n".join(out)


