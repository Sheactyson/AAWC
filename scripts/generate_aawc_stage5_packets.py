"""Generate persistent Stage 5 packets and integrated transaction helpers.

Native stories persist provenance and receipts. The transaction coordinator uses
AAWC cohort adapters; the canonical registry supplies identity ranks.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mod/AGOT_Alternate_World_Compatch'


def render():
    parts = ['''# Generated by generate_aawc_stage5_packets.py; do not hand edit.
# Persistent packet API used by production native migration routing.
# Province scope. SOURCE=this; DESTINATION=province; AMOUNT=whole persons.
# One pending packet per source. Do not replace a pending packet on retry.
aawc_stage5_begin_packet_effect = {
    if = {
        limit = {
            NOT = { has_variable = aawc_stage5_packet }
            exists = $DESTINATION$
            NOT = { this = $DESTINATION$ }
            $AMOUNT$ > 0
            has_variable = aawc_population_current
            var:aawc_population_current > $AMOUNT$
        }
        save_scope_as = aawc_stage5_source
        dummy_male = {
            create_story = { type = aawc_stage5_packet_record save_scope_as = aawc_stage5_packet }
        }
        scope:aawc_stage5_packet = {
            set_variable = { name = source value = scope:aawc_stage5_source }
            set_variable = { name = destination value = $DESTINATION$ }
            set_variable = { name = amount value = $AMOUNT$ }
            set_variable = { name = source_population value = scope:aawc_stage5_source.var:aawc_population_current }
            set_variable = { name = phase value = 0 }
            set_variable = { name = invalid value = 0 }
            set_variable = { name = whole_amount value = { value = var:amount floor = yes } }
            if = {
                limit = { NOT = { var:whole_amount = var:amount } }
                set_variable = { name = invalid value = 1 }
            }
            remove_variable = whole_amount
        }
        set_variable = { name = aawc_stage5_packet value = scope:aawc_stage5_packet }
        aawc_stage5_snapshot_axis_effect = { TYPE = culture }
        aawc_stage5_snapshot_axis_effect = { TYPE = faith }
    }
}

# Province scope; assemble once, independently for each axis.
# Persist values, not mutable CaFG struct references. Repairs are staged only;
# the integrating transaction must initialize the missing CaFG axis on commit.
aawc_stage5_snapshot_axis_effect = {
    if = {
        limit = { NOT = { scope:aawc_stage5_packet = { has_variable = $TYPE$_snapshot } } }
        save_scope_as = aawc_stage5_source
        scope:aawc_stage5_packet = {
            set_variable = { name = snapshot_count value = 0 }
            if = {
                limit = { exists = scope:aawc_stage5_source.barony.holder.$TYPE$ }
                set_variable = { name = owner_$TYPE$ value = scope:aawc_stage5_source.barony.holder.$TYPE$ }
            }
        }
        every_in_list = {
            variable = kCAFG_province_$TYPE$_structs
            save_scope_as = aawc_stage5_origin_struct
            dummy_male = {
                create_story = { type = aawc_stage5_packet_record save_scope_as = aawc_stage5_row }
            }
            scope:aawc_stage5_row = {
                set_variable = { name = identity value = scope:aawc_stage5_origin_struct.var:$TYPE$ }
                set_variable = { name = original_factor value = scope:aawc_stage5_origin_struct.var:factor }
                set_variable = { name = quantity value = 0 }
                aawc_stage5_snapshot_carry_effect = { TYPE = $TYPE$ }
            }
            scope:aawc_stage5_packet = {
                add_to_variable_list = { name = $TYPE$_rows target = scope:aawc_stage5_row }
                change_variable = { name = snapshot_count add = 1 }
            }
        }
        scope:aawc_stage5_packet = {
            if = {
                limit = { var:snapshot_count = 0 }
                if = {
                    limit = { exists = scope:aawc_stage5_source.county.$TYPE$ }
                    dummy_male = {
                        create_story = { type = aawc_stage5_packet_record save_scope_as = aawc_stage5_row }
                    }
                    scope:aawc_stage5_row = {
                        set_variable = { name = identity value = scope:aawc_stage5_source.county.$TYPE$ }
                        set_variable = { name = original_factor value = 1 }
                        set_variable = { name = quantity value = 0 }
                        aawc_stage5_snapshot_carry_effect = { TYPE = $TYPE$ }
                    }
                    add_to_variable_list = { name = $TYPE$_rows target = scope:aawc_stage5_row }
                    set_variable = { name = $TYPE$_repair value = 1 }
                }
                else = { set_variable = { name = invalid value = 1 } }
            }
            set_variable = { name = $TYPE$_snapshot value = 1 }
            remove_variable = snapshot_count
        }
    }
}

# Row scope. Source-owned carry records are keyed by identity, independently
# of CaFG struct lifetime. Duplicate records fail closed instead of list-order wins.
aawc_stage5_snapshot_carry_effect = {
    save_scope_as = aawc_stage5_row
    set_variable = { name = departure_carry value = 0 }
    set_variable = { name = carry_matches value = 0 }
    scope:aawc_stage5_source = {
        every_in_list = {
            variable = aawc_stage5_$TYPE$_carries
            limit = { var:identity = scope:aawc_stage5_row.var:identity }
            save_scope_as = aawc_stage5_carry
            scope:aawc_stage5_row = {
                set_variable = { name = departure_carry value = scope:aawc_stage5_carry.var:value }
                change_variable = { name = carry_matches add = 1 }
            }
        }
    }
    if = {
        limit = { var:carry_matches > 1 }
        scope:aawc_stage5_packet = { set_variable = { name = invalid value = 1 } }
    }
    remove_variable = carry_matches
}

# Packet scope; known identity quantities are set, never added on retry.
# Reject unknown identities and malformed quantities before any absolute debit.
aawc_stage5_set_packet_quantity_effect = {
    if = {
        limit = { var:phase = 0 }
        save_scope_as = aawc_stage5_packet
        set_variable = { name = matched value = 0 }
        every_in_list = {
            variable = $TYPE$_rows
            limit = { var:identity = $IDENTITY$ }
            set_variable = { name = quantity value = $QUANTITY$ }
            scope:aawc_stage5_packet = { set_variable = { name = $TYPE$_explicit value = 1 } }
            scope:aawc_stage5_packet = { change_variable = { name = matched add = 1 } }
        }
        if = {
            limit = { OR = { NOT = { var:matched = 1 } $QUANTITY$ < 0 } }
            set_variable = { name = invalid value = 1 }
        }
        remove_variable = matched
    }
}

# Packet scope. Revalidate persisted vectors against frozen source masses.
# A sealed packet cannot be edited. Phase 1 means provenance sealed, NOT debited.
aawc_stage5_seal_packet_effect = {
    if = {
        limit = { var:phase = 0 }
        save_scope_as = aawc_stage5_packet
        aawc_stage5_validate_axis_effect = { TYPE = culture }
        aawc_stage5_validate_axis_effect = { TYPE = faith }
        if = {
            limit = {
                var:invalid = 0
                var:culture_total = var:amount
                var:faith_total = var:amount
            }
            set_variable = { name = phase value = 1 }
        }
    }
}

aawc_stage5_validate_axis_effect = {
    set_variable = { name = $TYPE$_total value = 0 }
    set_variable = { name = $TYPE$_factor_total value = 0 }
    every_in_list = {
        variable = $TYPE$_rows
        set_variable = { name = whole_quantity value = { value = var:quantity floor = yes } }
        if = {
            limit = { NOT = { var:whole_quantity = var:quantity } }
            scope:aawc_stage5_packet = { set_variable = { name = invalid value = 1 } }
        }
        remove_variable = whole_quantity
        set_variable = { name = available value = var:original_factor }
        change_variable = { name = available multiply = scope:aawc_stage5_packet.var:source_population }
        if = {
            limit = { OR = { var:quantity < 0 var:quantity > var:available var:original_factor < 0 } }
            scope:aawc_stage5_packet = { set_variable = { name = invalid value = 1 } }
        }
        scope:aawc_stage5_packet = {
            change_variable = { name = $TYPE$_total add = prev.var:quantity }
            change_variable = { name = $TYPE$_factor_total add = prev.var:original_factor }
        }
        remove_variable = available
    }
    if = {
        limit = { NOT = { var:$TYPE$_factor_total = 1 } }
        set_variable = { name = invalid value = 1 }
    }
}

# Province scope. Cancel only uncommitted staging; never discard in-flight debt.
aawc_stage5_cancel_staging_effect = {
    if = {
        limit = {
            has_variable = aawc_stage5_packet
            var:aawc_stage5_packet = { var:phase < 2 }
        }
        var:aawc_stage5_packet = {
            every_in_list = { variable = culture_rows end_story = yes }
            every_in_list = { variable = faith_rows end_story = yes }
            end_story = yes
        }
        remove_variable = aawc_stage5_packet
    }
}
''']
    from generate_aawc_stage5_reconciliation import render_reconciliation
    parts.append(render_reconciliation())
    from generate_aawc_stage5_settlement import render_settlement
    parts.append(render_settlement())
    from generate_aawc_stage5_departures import render_departures
    parts.append(render_departures())
    from generate_aawc_stage5_routing import render_routing
    parts.append(render_routing())
    from generate_aawc_stage5_lifecycle import render_lifecycle
    parts.append(render_lifecycle())
    from generate_aawc_stage5_transactions import render_transactions
    parts.append(render_transactions())
    text = '\n'.join(parts)
    # The native effect call is synchronous. Permit the exact locked packet's
    # writes only for its commit; ordinary CaFG/cohort calls cannot borrow a
    # saved scope left behind by recovery or by an earlier proposal.
    from generate_aawc_stage3_buildings import matching_brace
    import re
    for name in ('commit_absolute_source', 'commit_absolute_destination', 'commit_absolute_refund',
                 'apply_source_debit', 'apply_destination_credit', 'apply_refund'):
        match = re.search(r'aawc_stage5_' + name + r'_effect\s*=\s*\{',text)
        start=match.end()-1; end=matching_brace(text,start)
        body=text[start+1:end]
        text=text[:start+1]+'\n    set_global_variable = { name = aawc_stage5_mutating_packet value = this }'+body+'    remove_global_variable = aawc_stage5_mutating_packet\n'+text[end:]
    return text


def main():
    out = MOD / 'common/scripted_effects/aawc_stage5_packet_effects.txt'
    out.write_text(render(), encoding='utf-8-sig', newline='\n')
    story = MOD / 'common/story_cycles/aawc_stage5_packets.txt'
    story.parent.mkdir(exist_ok=True)
    story.write_text('aawc_stage5_packet_record = {\n    on_setup = {}\n    on_end = {}\n    on_owner_death = {}\n}\n', encoding='utf-8-sig', newline='\n')


if __name__ == '__main__':
    main()
