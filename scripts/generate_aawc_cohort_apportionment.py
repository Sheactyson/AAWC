"""Generate the bounded Hamilton allocation primitive.

Thirteen capacity/weight slots correspond to the established age-band order.
Only scratch/output variables are written. No province residents, overlays,
carry, hook, runtime ID or existing production operation is replaced here.
The generated all-flows adapter consumes its outputs; integration certification
is separate from verification of this scratch-only core.
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mod/AGOT_Alternate_World_Compatch/common'
P = 'aawc_reforging_apportion_'
N = 13
VARIABLES = ['requested', 'remaining', 'valid', 'weight_sum', 'budget', 'saturated', 'best', 'winner', 'weight_limit']
VARIABLES += [f'{field}_{i:02}' for field in ('capacity', 'weight', 'active', 'quota', 'remainder', 'allocation') for i in range(N)]


def v(name):
    return P + name + '_value'


def setv(name, value):
    return f'set_variable = {{ name = {P}{name} value = {value} }}'


def add(name, value):
    # Read through a zero-safe value; CK3 may omit a zero-valued variable.
    return setv(name, f'{{ value = {v(name)} add = {value} }}')


def block(name, lines):
    return P + name + '_effect = {\n' + '\n'.join('\t' + line for line in lines) + '\n}\n'


def generate():
    header = ('# Generated by scripts/generate_aawc_cohort_apportionment.py.\n'
              '# Selected largest remainder core; consumed by the staged all-flows adapter.\n'
              '# Inputs: requested whole persons, 13 integer capacities and nonnegative weights.\n'
              '# Outputs: valid, allocation_00..12 and remaining (explicit unserved whole demand).\n'
              '# Ties: ascending established age-band index. Zero weights receive no allocation.\n'
              '# At most 13 saturation rounds and 13 final awards; never a per-person loop.\n'
              '# Conservative arithmetic envelope: requested * each weight <= 10^12.\n'
              '# Out-of-envelope input returns valid=0 and all demand unserved.\n'
              '# Call cleanup only after consuming outputs. No demographic state is mutated.\n\n')
    values = header + '\n'.join(
        P + name + '_value = {\n\tvalue = 0\n'
        + f'\tif = {{ limit = {{ has_variable = {P}{name} }} add = var:{P}{name} }}\n}}\n'
        for name in VARIABLES)
    initialize = [setv('valid', '1'), setv('remaining', v('requested'))]
    # Invalid caller input must not be silently rounded, normalized or consumed.
    initialize += [f'if = {{ limit = {{ {v("requested")} < 0 }} {setv("valid", "0")} }}',
                   setv('budget', f'{{ value = {v("requested")} floor = yes }}'),
                   f'if = {{ limit = {{ NOT = {{ {v("requested")} = {v("budget")} }} }} {setv("valid", "0")} }}']
    initialize += [setv('weight_limit', '1000000000000'),
                   f'if = {{ limit = {{ {v("requested")} > 0 }} '
                   + setv('weight_limit', f'{{ value = 1000000000000 divide = {v("requested")} }}') + ' }']
    for i in range(N):
        cap, weight, active, allocation = [f'{field}_{i:02}' for field in ('capacity', 'weight', 'active', 'allocation')]
        initialize += [setv(allocation, '0'), setv(active, '0'),
            setv('budget', f'{{ value = {v(cap)} floor = yes }}'),
            f'if = {{ limit = {{ OR = {{ {v(cap)} < 0 {v(weight)} < 0 {v(weight)} > {v("weight_limit")} NOT = {{ {v(cap)} = {v("budget")} }} }} }} {setv("valid", "0")} }}',
            f'if = {{ limit = {{ {v(cap)} > 0 {v(weight)} > 0 }} {setv(active, "1")} }}']
    initialize += ['if = {', f'\tlimit = {{ {v("valid")} = 1 }}']
    initialize += ['\t' + P + 'round_effect = yes'] * N
    initialize += ['}']

    round_body = ['if = {', f'\tlimit = {{ {v("remaining")} > 0 }}',
                  '\t' + setv('weight_sum', '0')]
    for i in range(N):
        round_body += [f'\tif = {{ limit = {{ {v(f"active_{i:02}")} = 1 }} {add("weight_sum", v(f"weight_{i:02}"))} }}']
    round_body += ['\tif = {', f'\t\tlimit = {{ {v("weight_sum")} > 0 }}',
                   '\t\t' + setv('budget', v('remaining')), '\t\t' + setv('saturated', '0')]
    for i in range(N):
        active, quota, weight, cap, allocation = [f'{field}_{i:02}' for field in ('active', 'quota', 'weight', 'capacity', 'allocation')]
        round_body += ['\t\tif = {', f'\t\t\tlimit = {{ {v(active)} = 1 }}',
            '\t\t\t' + setv(quota, f'{{ value = {v("budget")} multiply = {v(weight)} divide = {v("weight_sum")} floor = yes }}'),
            '\t\t\tif = {', f'\t\t\t\tlimit = {{ {v(quota)} >= {v(cap)} }}',
            '\t\t\t\t' + setv(allocation, v(cap)),
            '\t\t\t\t' + add('remaining', f'{{ value = {v(cap)} multiply = -1 }}'),
            '\t\t\t\t' + setv(active, '0'), '\t\t\t\t' + setv('saturated', '1'), '\t\t\t}', '\t\t}']
    round_body += ['\t\tif = {', f'\t\t\tlimit = {{ {v("saturated")} = 0 }}']
    for i in range(N):
        active, quota, weight, remainder, allocation = [f'{field}_{i:02}' for field in ('active', 'quota', 'weight', 'remainder', 'allocation')]
        # Rank the exact numerator, avoiding ties introduced by five-decimal division.
        round_body += ['\t\t\tif = {', f'\t\t\t\tlimit = {{ {v(active)} = 1 }}',
            '\t\t\t\t' + setv(allocation, v(quota)),
            '\t\t\t\t' + add('remaining', f'{{ value = {v(quota)} multiply = -1 }}'),
            '\t\t\t\t' + setv(remainder, f'{{ value = {v("budget")} multiply = {v(weight)} subtract = {{ value = {v(quota)} multiply = {v("weight_sum")} }} }}'), '\t\t\t}']
    round_body += ['\t\t\t' + P + 'award_effect = yes'] * N
    # No population-dependent retry. Positive remaining is visible to the caller.
    round_body += ['\t\t}', '\t}', '}']

    award = ['if = {', f'\tlimit = {{ {v("remaining")} > 0 }}', '\t' + setv('best', '-1'), '\t' + setv('winner', '0')]
    for i in range(N):
        award += [f'\tif = {{ limit = {{ {v(f"active_{i:02}")} = 1 {v(f"remainder_{i:02}")} > {v("best")} }} '
                  + setv('best', v(f'remainder_{i:02}')) + ' ' + setv('winner', str(i+1)) + ' }']
    for i in range(N):
        award += [f'\tif = {{ limit = {{ {v("winner")} = {i+1} }} '
                  + add(f'allocation_{i:02}', '1') + ' ' + setv(f'active_{i:02}', '0') + ' ' + add('remaining', '-1') + ' }']
    award += ['}']
    effects = header + '\n'.join((block('allocate', initialize), block('round', round_body), block('award', award),
                                  block('cleanup', [f'remove_variable = {P}{name}' for name in VARIABLES])))
    return {MOD / 'scripted_effects/aawc_reforging_cohort_apportionment_effects.txt': effects,
            MOD / 'script_values/aawc_reforging_cohort_apportionment_values.txt': values}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            assert path.read_bytes() == text.encode('utf-8-sig'), str(path)
        else:
            path.write_bytes(text.encode('utf-8-sig'))
        print(('Verified: ' if args.check else 'Generated: ') + str(path.relative_to(ROOT)))
