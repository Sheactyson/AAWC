"""Pin stable native identity/province keys for Stage 5.

--derive reads the effective installed stack once. Normal generation is portable
and uses the retained inventory. Dynamic identities receive immutable persisted
keys independently of CaFG factor-list order, including existing-save bootstrap.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

from aawc_paths import ROOT
from generate_aawc_stage3_buildings import matching_brace
from validate_aawc_reforging_stage1_cohort_engine import top_level_definitions, definition_body

MOD = ROOT / 'mod/AGOT_Alternate_World_Compatch'
INVENTORY = ROOT / 'catalogue/stage5/native_identity_registry.json'
OUTPUT = MOD / 'common/scripted_effects/aawc_stage5_registry_effects.txt'
HOOKS = MOD / 'common/on_action/aawc_stage5_identity_on_actions.txt'
DYNAMIC_START = 1000000


def derive(base, agot):
    roots = [('CK3', base), ('AGOT', agot), ('Dependencies', ROOT / 'dependencies/AAWC_Dependencies_Modpack'), ('AAWC', MOD)]
    hashes = {}

    def effective(category):
        files = {}
        for label, root in roots:
            descriptor = root / 'descriptor.mod'
            if descriptor.exists():
                replacements = re.findall(r'replace_path\s*=\s*"([^"]+)"', descriptor.read_text(encoding='utf-8-sig'))
                if any(category == p or category.startswith(p + '/') for p in replacements):
                    files.clear()
            for path in sorted((root / category).glob('*.txt')):
                files[path.name] = (label, path)
        for name, (label, path) in sorted(files.items()):
            hashes[label + '/' + category + '/' + name] = hashlib.sha256(path.read_bytes()).hexdigest()
            yield path.read_text(encoding='utf-8-sig')

    cultures = set()
    for text in effective('common/culture/cultures'):
        cultures.update(top_level_definitions(text))
    religions, faiths = set(), set()
    for text in effective('common/religion/religion_types'):
        for religion in top_level_definitions(text):
            body = definition_body(text, religion)
            religions.add(religion)
            match = re.search(r'\bfaiths\s*=\s*\{', body)
            if match:
                start = match.end() - 1
                faiths.update(top_level_definitions(body[start+1:matching_brace(body, start)]))
    provinces = set()
    for text in effective('common/landed_titles'):
        # Landed-title province assignments are numeric leaves, not save IDs.
        text = re.sub(r'#[^\n]*', '', text)
        provinces.update(int(n) for n in re.findall(r'\bprovince\s*=\s*(\d+)\b', text))
    assert cultures and faiths and religions and provinces
    return dict(schema=1, culture=sorted(cultures), faith=sorted(faiths), religions=sorted(religions),
                provinces=sorted(provinces), source_sha256=hashes,
                dynamic_key='Persistent ordinal >=1000000 assigned at creation; existing identities bootstrap once in native registry order, never factor-list order.')


def render_registry(data):
    lines = ['# Generated by generate_aawc_stage5_registry.py. Static key order is lexical.',
             '# Dynamic keys are immutable saved ordinals; never assign from CaFG row order.',
             'aawc_stage5_ensure_registry_effect = {',
             '    if = {', '        limit = { NOT = { has_global_variable = aawc_stage5_registry_ready } }']
    for axis in ('culture', 'faith'):
        lines.append(f'        if = {{ limit = {{ NOT = {{ has_global_variable = aawc_stage5_next_{axis}_key }} }} set_global_variable = {{ name = aawc_stage5_next_{axis}_key value = {DYNAMIC_START} }} }}')
        for rank, key in enumerate(data[axis], 1):
            lines.append(f'        {axis}:{key} = {{ set_variable = {{ name = aawc_stage5_identity_rank value = {rank} }} }}')
    for pid in data['provinces']:
        lines.append(f'        province:{pid} = {{ set_variable = {{ name = aawc_stage5_province_id value = {pid} }} }}')
    lines.extend(['        every_culture_global = { aawc_stage5_register_dynamic_identity_effect = { TYPE = culture } }'])
    for religion in data['religions']:
        lines.append(f'        religion:{religion} = {{ every_faith = {{ aawc_stage5_register_dynamic_identity_effect = {{ TYPE = faith }} }} }}')
    lines.extend(['        set_global_variable = { name = aawc_stage5_registry_ready value = 1 }', '    }', '}',
        '', '# Culture/faith scope. Creation hook and bootstrap both call this idempotently.',
        'aawc_stage5_register_dynamic_identity_effect = {',
        '    if = {', '        limit = { NOT = { has_variable = aawc_stage5_identity_rank } }',
        '        if = { limit = { NOT = { has_global_variable = aawc_stage5_next_$TYPE$_key } } set_global_variable = { name = aawc_stage5_next_$TYPE$_key value = 1000000 } }',
        '        set_variable = { name = aawc_stage5_identity_rank value = global_var:aawc_stage5_next_$TYPE$_key }',
        '        change_global_variable = { name = aawc_stage5_next_$TYPE$_key add = 1 }',
        '    }', '}', ''])
    return '\n'.join(lines)


def render_hooks():
    return '''# Append to native on-actions; do not replace their existing effects.
on_culture_created = { on_actions = { aawc_stage5_culture_created } }
on_faith_created = { on_actions = { aawc_stage5_faith_created } }
aawc_stage5_culture_created = {
    effect = { aawc_stage5_register_dynamic_identity_effect = { TYPE = culture } }
}
aawc_stage5_faith_created = {
    effect = { faith = { aawc_stage5_register_dynamic_identity_effect = { TYPE = faith } } }
}
'''


def build():
    data = json.loads(INVENTORY.read_text(encoding='utf-8'))
    return {OUTPUT:render_registry(data), HOOKS:render_hooks()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--derive', action='store_true')
    parser.add_argument('--base', type=Path)
    parser.add_argument('--agot', type=Path)
    args = parser.parse_args()
    if args.derive:
        assert args.base and args.agot, '--derive requires explicit installed roots'
        INVENTORY.write_text(json.dumps(derive(args.base, args.agot), indent=2)+'\n', encoding='utf-8')
    for path, text in build().items():
        path.write_text(text, encoding='utf-8-sig', newline='\n')
    print('Generated stable identity/province registry and creation hooks')
